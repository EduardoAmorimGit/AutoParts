package com.autoparts_maven.autoparts_maven.payment.dto;

import com.autoparts_maven.autoparts_maven.payment.Payment;
import com.autoparts_maven.autoparts_maven.payment.gateway.PaymentGateway.Challenge;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;
import java.math.BigDecimal;
import java.time.Instant;

public final class PaymentDtos {

    private PaymentDtos() {
    }

    /** CPF is optional for Pix; when given it is sent as the payer identification. */
    public record PixPaymentRequest(
            @Pattern(regexp = "^\\d{3}\\.?\\d{3}\\.?\\d{3}-?\\d{2}$", message = "must be a CPF") String cpf) {
    }

    /** Card data stays in the browser: only the token generated by Mercado Pago's Card Payment Brick comes here. */
    public record CardPaymentRequest(
            @NotBlank @Size(max = 200) String token,
            @NotBlank @Size(max = 40) String paymentMethodId,
            @Size(max = 40) String issuerId,
            @Min(1) @Max(12) int installments,
            @NotBlank @Pattern(regexp = "^(CPF|CNPJ)$") String identificationType,
            @NotBlank @Pattern(regexp = "^[\\d./-]{11,18}$") String identificationNumber) {
    }

    public record PixData(String qrCode, String qrCodeBase64, String ticketUrl, Instant expiresAt) {
    }

    public record ChallengeData(String url, String creq) {
    }

    public record PaymentResponse(Long id, Long orderId, String method, String status, String statusDetail,
            BigDecimal amount, PixData pix, ChallengeData challenge, Instant approvedAt, boolean needsAttention,
            String attentionReason, Instant createdAt) {

        public static PaymentResponse from(Payment payment, Challenge challenge) {
            PixData pix = payment.getPixQrCode() == null ? null : new PixData(payment.getPixQrCode(),
                    payment.getPixQrCodeBase64(), payment.getPixTicketUrl(), payment.getExpiresAt());
            return new PaymentResponse(payment.getId(), payment.getOrderId(), payment.getMethod().name(),
                    payment.getStatus().name(), payment.getProviderStatusDetail(), payment.getAmount(), pix,
                    challenge == null ? null : new ChallengeData(challenge.url(), challenge.creq()),
                    payment.getApprovedAt(), payment.isNeedsAttention(), payment.getAttentionReason(),
                    payment.getCreatedAt());
        }
    }
}
